-- =====================================================================
-- MuleWatch :: 10_governance.sql  - Horizon governance
--   * Tag-based dynamic masking of PII (analysts see masked values, managers see clear text)
--   * Row access policy: analysts only see cases/accounts of their mapped regions
--   * Least-privilege grants; ground truth & audit invisible to analysts
-- Run AFTER the pipeline (policies are attached to existing tables).
-- =====================================================================
USE ROLE MULEWATCH_ADMIN;
USE DATABASE MULEWATCH;
USE WAREHOUSE MULEWATCH_WH;

CREATE TAG IF NOT EXISTS GOV.PII ALLOWED_VALUES 'NAME', 'CONTACT', 'GOVT_ID', 'DOB'
  COMMENT = 'Personally identifiable information class';

CREATE OR REPLACE MASKING POLICY GOV.MASK_PII AS (VAL STRING) RETURNS STRING ->
  CASE
    WHEN VAL IS NULL THEN NULL
    WHEN IS_ROLE_IN_SESSION('FINCRIME_MANAGER')
      OR CURRENT_ROLE() IN ('MULEWATCH_ADMIN', 'ACCOUNTADMIN', 'SYSADMIN') THEN VAL
    WHEN SYSTEM$GET_TAG_ON_CURRENT_COLUMN('MULEWATCH.GOV.PII') = 'NAME'
      THEN LEFT(VAL, 1) || '***** ' || SPLIT_PART(VAL, ' ', -1)
    WHEN SYSTEM$GET_TAG_ON_CURRENT_COLUMN('MULEWATCH.GOV.PII') = 'GOVT_ID'
      THEN 'XXXXXX' || RIGHT(VAL, 4)
    ELSE '*** masked ***'
  END
  COMMENT = 'PII visible only to FINCRIME_MANAGER and above';

ALTER TAG GOV.PII SET MASKING POLICY GOV.MASK_PII;

ALTER TABLE RAW.CUSTOMERS MODIFY
  COLUMN FULL_NAME SET TAG GOV.PII = 'NAME',
  COLUMN PHONE     SET TAG GOV.PII = 'CONTACT',
  COLUMN EMAIL     SET TAG GOV.PII = 'CONTACT',
  COLUMN PAN       SET TAG GOV.PII = 'GOVT_ID';


-- ---------------------------------------------------------------------
-- Least-privilege grants for the analyst role
-- ---------------------------------------------------------------------
GRANT USAGE ON DATABASE MULEWATCH TO ROLE FINCRIME_ANALYST;
