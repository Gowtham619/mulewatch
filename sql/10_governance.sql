USE ROLE MULEWATCH_ADMIN;
USE DATABASE MULEWATCH;
USE WAREHOUSE MULEWATCH_WH;



-- ---------------------------------------------------------------------
-- Least-privilege grants for the analyst role
-- ---------------------------------------------------------------------
GRANT USAGE ON DATABASE MULEWATCH TO ROLE FINCRIME_ANALYST;
GRANT USAGE ON SCHEMA MULEWATCH.ANALYTICS TO ROLE FINCRIME_ANALYST;
GRANT USAGE ON SCHEMA MULEWATCH.CURATED   TO ROLE FINCRIME_ANALYST;
GRANT USAGE ON SCHEMA MULEWATCH.AI        TO ROLE FINCRIME_ANALYST;
GRANT USAGE ON SCHEMA MULEWATCH.APP       TO ROLE FINCRIME_ANALYST;
GRANT USAGE ON SCHEMA MULEWATCH.RAW       TO ROLE FINCRIME_ANALYST;
GRANT SELECT ON ALL TABLES IN SCHEMA MULEWATCH.ANALYTICS TO ROLE FINCRIME_ANALYST;
GRANT SELECT ON ALL VIEWS  IN SCHEMA MULEWATCH.ANALYTICS TO ROLE FINCRIME_ANALYST;
GRANT SELECT ON ALL DYNAMIC TABLES IN SCHEMA MULEWATCH.CURATED TO ROLE FINCRIME_ANALYST;
GRANT SELECT ON ALL TABLES IN SCHEMA MULEWATCH.AI TO ROLE FINCRIME_ANALYST;
GRANT SELECT ON TABLE MULEWATCH.RAW.CUSTOMERS TO ROLE FINCRIME_ANALYST;   -- masked
GRANT SELECT ON TABLE MULEWATCH.RAW.FRAUD_COMPLAINTS TO ROLE FINCRIME_ANALYST;
GRANT SELECT ON TABLE MULEWATCH.RAW.DOCS TO ROLE FINCRIME_ANALYST;
GRANT SELECT, REFERENCES ON SEMANTIC VIEW MULEWATCH.ANALYTICS.FINCRIME_SV TO ROLE FINCRIME_ANALYST;
GRANT USAGE ON CORTEX SEARCH SERVICE MULEWATCH.AI.POLICY_SEARCH    TO ROLE FINCRIME_ANALYST;
GRANT USAGE ON CORTEX SEARCH SERVICE MULEWATCH.AI.MEDIA_SEARCH     TO ROLE FINCRIME_ANALYST;
GRANT USAGE ON CORTEX SEARCH SERVICE MULEWATCH.AI.COMPLAINT_SEARCH TO ROLE FINCRIME_ANALYST;
GRANT USAGE ON PROCEDURE MULEWATCH.APP.GET_CASE_BRIEF(VARCHAR) TO ROLE FINCRIME_ANALYST;
GRANT USAGE ON PROCEDURE MULEWATCH.APP.RECORD_DISPOSITION(VARCHAR, VARCHAR, VARCHAR, VARCHAR) TO ROLE FINCRIME_MANAGER;
-- NOTE: no grants on GOV.GROUND_TRUTH or GOV.AGENT_AUDIT_LOG to analysts.

-- Audit-friendly view for compliance reviewers (managers)
CREATE OR REPLACE VIEW GOV.V_AI_ACTIVITY AS
SELECT EVENT_TS, AGENT, ACTION, CASE_ID, MODEL, STATUS, DURATION_MS, INVOKED_BY, DETAILS
FROM GOV.AGENT_AUDIT_LOG;
GRANT USAGE ON SCHEMA MULEWATCH.GOV TO ROLE FINCRIME_MANAGER;
GRANT SELECT ON VIEW MULEWATCH.GOV.V_AI_ACTIVITY TO ROLE FINCRIME_MANAGER;

